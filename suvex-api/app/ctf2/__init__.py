"""CTF2 平台对接领域。

## 这个模块做什么

绑定 CTF2 账号 → 同步赛事与题目 → 起题目环境 → 调度 LLM 在**独立沙箱**
里解题 → 校验候选 flag → 提交 → 事件写进活动流。

## ★ 它与 `scans` 的分工（这是本模块最容易做错的一处）

两者都要"让 LLM 去打一个目标"，所以看起来该复用 `scans`。
**刻意不复用**，理由是我们对目标的**知情程度**完全不同：

| | `scans` | `ctf2` |
| --- | --- | --- |
| 目标是谁的 | **别人的**（客户资产，有法律边界） | 题目容器（平台给的，用完即销毁） |
| 题目是什么 | 未知，要 agent 自己找 | **平台已经告诉我们**（分类、题面、附件） |
| 成功判据 | 一堆发现物 + 报告 | 一个 flag 字符串，平台**会判定对错** |
| 要不要授权声明 | **必须**（契约 §5） | 不需要 —— 平台自己就是授权方 |
| 谁的凭据 | 用户自己的 LLM key | 用户自己的 PAT + LLM key |

硬塞进 `scans` 的后果很具体：`POST /scans` 的授权确认是**逐字校验**的
（契约 §5.2），而 CTF2 的解题请求**不该**要求用户为每道题签一次法律声明 ——
那会让这道防线因为"天天要点"而退化成肌肉记忆，**反而削弱了它**。
法律留痕的价值来自它稀有且被认真对待。

所以：**复用执行机制（Docker 容器编排、litellm 网关、events 流），
不复用业务流程（授权、判据、结果模型）**。

⚠️ 但有一条**必须**复用：CTF2 的解题任务会建一条真实的 `Scan` 行 ——
因为 `activity_events.scan_id` 是非空外键，而"前端 Activity 页面零改动
就能看到进度"（已定设计决策 7）只能靠这个落地。见 `events.py`。

## 目录内分工

· `client.py`   —— CTF2 Open API 的 HTTP 客户端。**唯一**与外部平台讲话的地方。
· `models.py`   —— 五张表（账号 / 赛事 / 题目 / 提交 / 环境）。
· `schemas.py`  —— 出入参。
· `service.py`  —— 业务编排（同步、绑定、受理、提交决策）。
· `router.py`   —— HTTP 端点。**只做薄封装。**
· `runner.py`   —— 单题 worker（起环境 → 沙箱 → 解题循环 → 候选 flag）。
· `scheduler.py`—— 题目队列 + 并发上限 + 孤儿回收。
· `events.py`   —— 进度事件 → 现有 events 流。
"""
