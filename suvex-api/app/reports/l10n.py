_TABLE: dict[str, dict[str, str]] = {"zh-CN": _ZH, "en": _EN, "ja": _JA}


def normalize(locale: str | None) -> str:
    """未知语言回落英文；`zh-TW` 与 `zh-CN` 共用中文表。"""
    if not locale:
        return "zh-CN"
    if locale.startswith("zh"):
        return "zh-CN"
    return locale if locale in SUPPORTED else "en"


def t(locale: str | None, key: str, **vars: Any) -> str:
    table = _TABLE[normalize(locale)]
    raw = table.get(key) or _EN.get(key) or _ZH.get(key) or key
    if vars:
        raw = raw.format(**vars)
    return raw


def date_format(locale: str) -> str:
    return normalize(locale)


_MONTHS = (
    "Jan", "Feb", "Mar", "Apr", "May", "Jun",
    "Jul", "Aug", "Sep", "Oct", "Nov", "Dec",
)


def format_date(value: Any, locale: str = "zh-CN") -> str:
    from app.reports.document import _parse

    parsed = _parse(value)
    if parsed is None:
        return str(value or "")
    loc = normalize(locale)
    if loc == "en":
        return f"{_MONTHS[parsed.month - 1]} {parsed.day}, {parsed.year}"
    return f"{parsed.year}年{parsed.month}月{parsed.day}日"


def format_datetime(value: Any, locale: str = "zh-CN") -> str:
    from app.reports.document import _parse

    parsed = _parse(value)
    if parsed is None:
        return str(value or "")
    return f"{format_date(value, locale)} {parsed.hour:02d}:{parsed.minute:02d}"
