/**
 * 对账脚本的**空检查防线**：确保每个脚本真的查了东西。
 *
 * ══════════════════════════════════════════════════════════════
 * 要解决的问题：**"全部通过"可能是一句谎话**
 * ══════════════════════════════════════════════════════════════
 *
 * 这些脚本的判定结构都是同一个形状：
 *
 *     let failures = 0
 *     for (const item of 清单) { ...出错就 failures += 1... }
 *     if (failures > 0) process.exitCode = 1
 *
 * 它有一个**完全静默**的失效模式：**如果清单是空的、或者遍历到 0 个目标**，
 * 循环一次都不执行，`failures` 永远是 0，脚本打印"✓ 全部通过"并返回 0。
 *
 * 于是它从"检查"退化成"**永远为真的空检查**" —— 比没有检查更危险，
 * 因为它会让人以为查过了。
 *
 * 本项目已经真踩过这个坑（`scripts/endpoint-parity.mjs` 的注释里记着）：
 * 路径少写一层 `app/`，脚本扫到 **0 个端点**却报绿——
 *
 *     ✓ 共扫描 0 个端点，缺失 0 个。
 *     ══ 契约覆盖了后端全部端点 ══
 *
 * 那是"永远为真的空检查"最典型的形态。
 *
 * ══════════════════════════════════════════════════════════════
 * 这个模块提供什么
 * ══════════════════════════════════════════════════════════════
 *
 * `createAudit()` 返回一个计数器 + 一个 `finish()`：
 *
 *   · 每条检查**必须**先 `audit.check()` 再判通过/失败 —— 计数与结论绑在一起，
 *     不存在"忘了计数但结论照出"的路径；
 *   · `finish()` 断言 `checks > 0`，为 0 时**以非零码退出并说明原因**；
 *   · 它同时打印实际检查了多少条，让"这次到底查了什么"可见 ——
 *     数字突然从 35 掉到 3，看日志就能发现。
 *
 * ## 为什么不只是"在脚本末尾加一句 if (checks === 0) 退出"
 *
 * 那确实能挡住"0 条"，但挡不住**少了很多条**（比如清单被误删了一半，
 * 检查了几条、其余静默消失）。所以除了 `checks > 0`，`finish()` 还接受
 * 一个 `minChecks` —— 每个脚本按自己的清单规模给一个下限，
 * 规模明显萎缩时会红。这个下限**不是精确值**（那会让每次正常增删都变红，
 * 红几次就没人看了），而是"数量级"级别的护栏。
 */

/**
 * @param {object} options
 * @param {string} options.name 脚本名（进日志，便于定位是哪个脚本空了）
 * @param {number} [options.minChecks] 至少应执行多少条检查。默认 1。
 * @returns {{ check: () => void, count: () => number, finish: (opts?: object) => void }}
 */
export function createAudit({ name, minChecks = 1 }) {
  let checks = 0

  return {
    /** 记录"执行了一条检查"。每一条检查都要调一次，无论通过还是失败。 */
    check() {
      checks += 1
    },

    /** 当前已执行的检查条数（供脚本内部需要时读）。 */
    count() {
      return checks
    },

    /**
     * 收尾：断言"确实查了东西"，并决定退出码。
     *
     * @param {object} [opts]
     * @param {number} [opts.failures] 发现的失败条数
     * @param {string} [opts.okMessage] 全绿时的结语
     * @param {string} [opts.failMessage] 有失败时的结语（会附上条数）
     */
    finish({ failures = 0, okMessage = '', failMessage = '' } = {}) {
      /*
        ★ 先把"这道防线本身还在不在"钉死。

        ## 为什么需要这一句（变异验证抓出来的）

        我对 `finish()` 做过变异验证：把下面那个 `checks === 0` 判断
        改成 `if (false)`（模拟有人手滑删掉防线），然后跑
        `verify-guards.mjs` —— 结果它**照样绿**。

        原因：`checks < minChecks` 那道判断把零检查也兜住了
        （`0 < 1` 成立），于是"零检查"这一条路径**被掩盖**了。
        换句话说，防线是否有效**依赖 minChecks 恰好 > 0** ——
        而 `minChecks` 是一个调用方随手能改的数字，改成 0 就全废了。

        所以这里显式拒绝 `minChecks <= 0`：让"下限"这个参数**不可能**
        成为绕过零检查的通道。两道判断各管一件事，语义不重叠：

          · `checks === 0`  → 这个脚本**没在检查任何东西**（事故）
          · `checks < minChecks` → 查了，但规模明显萎缩（清单被删）

        ⚠️ 它们必须**分别**可触发，否则变异验证会给出假绿。
      */
      if (!(minChecks > 0)) {
        console.log(
          `\n❌ [${name}] 内部错误：minChecks 必须 > 0（当前 ${minChecks}）。\n` +
            '   取 0 会让"一条检查都没执行"这道防线失效 —— 见 _audit.mjs 的说明。',
        )
        process.exitCode = 1
        return
      }

      // ── 先判"空检查"，因为它的结论具有**压倒性** ──
      //
      // 一个什么都没查的脚本，就算 failures 是 0 也毫无意义 ——
      // 所以这一条必须优先于"全部通过"那句结语输出，
      // 否则人只会看到最后一行"✓ 全部通过"。
      if (checks === 0) {
        console.log(
          `\n❌ [${name}] 一条检查都没执行 —— 这个脚本**没有在检查任何东西**。\n` +
            '   常见的三个原因：\n' +
            '     · 清单/路径写错了，遍历到 0 个目标；\n' +
            '     · 上游文件被改名或移动，新路径没同步到这里；\n' +
            '     · 过滤条件写得太严（例如前缀不匹配），把所有目标都筛掉了。\n' +
            '   ⚠️ 这比"报红"严重：它会输出"全部通过"而实际什么都没查。',
        )
        process.exitCode = 1
        return
      }

      if (checks < minChecks) {
        console.log(
          `\n❌ [${name}] 只执行了 ${checks} 条检查（下限 ${minChecks}）。\n` +
            '   规模明显萎缩，多半是清单被误删了，或过滤条件变严了。\n' +
            '   如果这是**有意的**（比如删掉了一批枚举），请同步调整本脚本的 minChecks。',
        )
        process.exitCode = 1
        return
      }

      console.log(`（本脚本实际执行了 ${checks} 条检查）`)

      if (failures > 0) {
        console.log(`\n${failMessage || `══ 发现 ${failures} 处不一致 ══`}`)
        process.exitCode = 1
        return
      }
      if (okMessage) console.log(`\n${okMessage}`)
    },
  }
}
